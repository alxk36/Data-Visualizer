const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {_electron:electron}=require(process.env.DV_PLAYWRIGHT_PATH || 'playwright');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'test-results');
let app;
(async()=>{
  await fs.mkdir(output,{recursive:true});
  const run=path.join(output,`run-${Date.now()}`);
  await fs.mkdir(run,{recursive:true});
  const profile=path.join(run,'profile');
  const fixture=path.join(run,'Measurements.dv');
  const csv=path.join(run,'Second.csv');
  await fs.writeFile(csv,'month,value\nJan,42\nFeb,57\n');
  app=await electron.launch({executablePath:path.join(root,'node_modules/electron/dist/electron.exe'),args:[root],env:{...process.env,DV_USER_DATA_DIR:profile},timeout:30000});
  const page=await app.firstWindow();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.waitForSelector('#welcome:not(.hidden)');
  await page.screenshot({path:path.join(output,'welcome.png')});
  await page.getByRole('button',{name:'Create new file'}).click();
  await page.locator('#editor').fill('month,value\nJan,42\nFeb,57\n');
  assert.equal(await page.locator('#line-gutter [data-line]').count(),4);
  await app.evaluate(({dialog},filePath)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath});},fixture);
  await page.keyboard.press('Control+s');
  await page.waitForFunction(()=>document.querySelector('#status-message').textContent==='Saved locally');
  const saved=JSON.parse(await fs.readFile(fixture,'utf8'));
  assert.equal(saved.content,'month,value\nJan,42\nFeb,57\n');
  await page.locator('#editor').fill('month,value\nJan,43\nFeb,58\n');
  await page.keyboard.press('Control+s');
  await page.waitForFunction(()=>document.querySelector('#status-message').textContent==='Saved locally');
  await page.locator('#history-button').click();
  await page.waitForSelector('#dialog[open]');
  assert.equal(await page.locator('.history-row').count(),2);
  await page.getByRole('button',{name:'Close dialog'}).click();
  await app.evaluate(({dialog},filePath)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[filePath]});},csv);
  await page.keyboard.press('Control+o');
  await page.waitForFunction(()=>document.querySelectorAll('#text-tabs .tab').length===2);
  await page.locator('#layout-button').click();
  await page.getByRole('menuitem',{name:'Visualizer only view',exact:true}).click();
  assert.equal(await page.locator('#editor').isVisible(),false);
  // Saving follows the active visualizer even when the text pane shows another file.
  await page.locator('#visualizer-tabs .tab').filter({hasText:'Measurements.dv'}).click();
  await page.keyboard.press('Control+s');
  await page.waitForFunction(()=>document.querySelector('#toast').textContent==='Saved Measurements.dv');
  await page.locator('#layout-button').click();
  await page.getByRole('menuitem',{name:'Text only view',exact:true}).click();
  assert.equal(await page.locator('#visualizer-pane').isVisible(),false);
  await page.locator('#layout-button').click();
  await page.getByRole('menuitem',{name:'Split view',exact:true}).click();
  // Restore both panes to the same file before exercising drag behavior.
  await page.locator('#file-list [data-doc]').filter({hasText:'Second.csv'}).click();
  await page.keyboard.press('Control+Shift+m');
  assert.equal(await page.locator('.activity-bar').isVisible(),false);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.activity-bar').isVisible(),true);
  await page.keyboard.press('Control+b');
  assert.equal(await page.locator('#explorer').isVisible(),false);
  await page.keyboard.press('Control+b');
  // Reordering tabs and moving across panes retain the document and its text.
  await page.locator('#text-tabs .tab').nth(1).dragTo(page.locator('#text-tabs .tab').nth(0));
  assert.match(await page.locator('#text-tabs .tab').first().textContent(),/Second.csv/);
  await page.locator('#text-tabs .tab').first().dragTo(page.locator('#visualizer-tabs .tab').first());
  await page.waitForFunction(()=>document.querySelectorAll('#text-tabs .tab').length===1);
  assert.equal(await page.locator('#visualizer-tabs .tab').count(),2);
  await page.locator('#file-list [data-doc]').filter({hasText:'Second.csv'}).dragTo(page.locator('#editor-surface'));
  await page.waitForFunction(()=>document.querySelectorAll('#text-tabs .tab').length===2);
  assert.equal(await page.locator('#editor').inputValue(),'month,value\nJan,42\nFeb,57\n');
  await page.keyboard.press('Control+f');
  await page.locator('#find-input').fill('Feb');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#find-result').textContent(),'1 match');
  await page.keyboard.press('Escape');
  await page.screenshot({path:path.join(output,'workspace.png')});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(560,480));
  await page.waitForFunction(()=>window.innerWidth<=560);
  const fit=await page.evaluate(()=>{const menu=document.querySelector('.main-menu').getBoundingClientRect();const controls=document.querySelector('.native-controls-space').getBoundingClientRect();return {left:menu.left,right:menu.right,controls:controls.left,width:innerWidth,scroll:document.body.scrollWidth};});
  assert.ok(fit.right<fit.controls,JSON.stringify(fit));
  assert.ok(fit.scroll<=fit.width,JSON.stringify(fit));
  await page.screenshot({path:path.join(output,'minimum-window.png')});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1440,920));
  // Confirm that canceling window closure retains the unsaved document.
  await page.locator('#editor').fill('unsaved content');
  await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:2});});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close());
  await page.waitForFunction(()=>document.querySelector('#editor').value==='unsaved content');
  assert.equal(app.windows().length,1);
  assert.deepEqual(errors,[]);
  console.log('UI smoke checks passed: create/save/history/open, layouts, focus, explorer, drag tabs, explorer drop, find, minimum size, canceled close.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(app){await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().forEach(win=>win.destroy())).catch(()=>{});await app.close().catch(()=>{});}});
