const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {_electron:electron}=require(process.env.DV_PLAYWRIGHT_PATH || 'playwright');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'test-results',`packaged-${Date.now()}`);
const executablePath=path.join(root,require('../package.json').build.directories.output,'win-unpacked','Data Visualizer.exe');
let app;
(async()=>{
  await fs.mkdir(output,{recursive:true});
  const first=path.join(output,'Launch test.dv'),second=path.join(output,'Second launch.dv');
  const encode=content=>JSON.stringify({format:'data-visualizer',version:1,content});
  await fs.writeFile(first,encode('Opened directly from a .dv file.'));
  await fs.writeFile(second,encode('Opened in the existing application.'));
  const userData=path.join(output,'profile');
  app=await electron.launch({executablePath,args:[`--user-data-dir=${userData}`,first],timeout:30000});
  const page=await app.firstWindow();
  await page.waitForFunction(()=>document.querySelector('#editor')?.value==='Opened directly from a .dv file.');
  assert.equal(await page.locator('#welcome').isVisible(),false);
  assert.equal((await page.locator('.canvas-tag').textContent()).trim(),'Data Visualizer');
  assert.equal(await app.evaluate(({app})=>app.getVersion()),require('../package.json').version);
  const secondProcess=spawn(executablePath,[`--user-data-dir=${userData}`,second],{windowsHide:true,stdio:'ignore'});
  await page.waitForFunction(()=>document.querySelector('#editor')?.value==='Opened in the existing application.');
  assert.equal(await page.locator('#text-tabs .tab').count(),2);
  await page.locator('#text-tabs .tab').last().click({button:'right'});
  assert.equal(await page.locator('.tab-context-menu [data-tab-action]').count(),12);
  await page.locator('.tab-context-menu [data-tab-action="split-right"]').click();
  assert.equal(await page.locator('#text-groups .editor-group').count(),2);
  assert.equal(await page.locator('#visualizer-groups .editor-group').count(),1);
  assert.ok(await page.evaluate(()=>document.querySelector('#text-pane-label').getBoundingClientRect().bottom<document.querySelector('#text-groups .tab').getBoundingClientRect().top));
  await new Promise((resolve,reject)=>{if(secondProcess.exitCode!==null)resolve();else{secondProcess.once('exit',resolve);secondProcess.once('error',reject);}});
  assert.equal(app.windows().length,1);
  const native=await app.evaluate(({BrowserWindow,app})=>{const win=BrowserWindow.getAllWindows()[0];return {minimum:win.getMinimumSize(),packaged:app.isPackaged,title:win.getTitle(),userData:app.getPath('userData')};});
  assert.equal(native.packaged,true);
  assert.deepEqual(native.minimum,[560,480]);
  assert.equal(path.normalize(native.userData),path.normalize(userData));
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].maximize());
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isMaximized()),true);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].unmaximize());
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].minimize());
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isMinimized()),true);
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].restore());
  console.log('Packaged checks passed: version and visualizer label, cold .dv launch, second-instance file opening, selected tab menu, pane-contained splits, title positioning, isolated profile, native window controls.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(app){await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().forEach(win=>win.destroy())).catch(()=>{});await app.close().catch(()=>{});}});
